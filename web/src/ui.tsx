import type { ButtonHTMLAttributes, ReactNode } from 'react'
import { useEffect } from 'react'
import type { RequestStatus } from './api'

type Tone = 'neutral' | 'info' | 'good' | 'warn' | 'bad'

const TONES: Record<Tone, string> = {
  neutral: 'bg-slate-100 text-slate-700 ring-slate-200',
  info: 'bg-sky-50 text-sky-800 ring-sky-200',
  good: 'bg-emerald-50 text-emerald-800 ring-emerald-200',
  warn: 'bg-amber-50 text-amber-900 ring-amber-200',
  bad: 'bg-rose-50 text-rose-800 ring-rose-200',
}

export function Badge({ tone = 'neutral', children, title }: { tone?: Tone; children: ReactNode; title?: string }) {
  return (
    <span title={title} className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-xs font-medium ring-1 ring-inset ${TONES[tone]}`}>
      {children}
    </span>
  )
}

const STATUS: Record<RequestStatus, { label: string; tone: Tone }> = {
  Draft: { label: 'Draft', tone: 'neutral' },
  Submitted: { label: 'Waiting for review', tone: 'info' },
  SentBack: { label: 'Sent back', tone: 'warn' },
  Approved: { label: 'Approved, creating in SAP', tone: 'info' },
  Creating: { label: 'Creating in SAP', tone: 'info' },
  Created: { label: 'Created in SAP', tone: 'good' },
  CreationFailed: { label: 'SAP creation failed', tone: 'bad' },
}

export function StatusBadge({ status }: { status: RequestStatus }) {
  return <Badge tone={STATUS[status].tone}>{STATUS[status].label}</Badge>
}

/** Marks a PR number that came from the mock adapter. Shown wherever such a number appears. */
export function SimulatedTag() {
  return (
    <Badge tone="warn" title="Generated by the mock SAP adapter. No purchase requisition exists in SAP.">
      SIMULATED
    </Badge>
  )
}

type ButtonVariant = 'primary' | 'secondary' | 'danger' | 'ghost'

const BUTTONS: Record<ButtonVariant, string> = {
  primary: 'bg-teal-700 text-white hover:bg-teal-800 disabled:bg-slate-300',
  secondary: 'bg-white text-slate-800 ring-1 ring-inset ring-slate-300 hover:bg-slate-50 disabled:text-slate-400',
  danger: 'bg-white text-rose-700 ring-1 ring-inset ring-rose-300 hover:bg-rose-50 disabled:text-slate-400 disabled:ring-slate-200',
  ghost: 'text-slate-600 hover:bg-slate-100 disabled:text-slate-300',
}

export function Button({
  variant = 'secondary',
  small,
  className = '',
  ...props
}: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: ButtonVariant; small?: boolean }) {
  return (
    <button
      type="button"
      {...props}
      className={`inline-flex items-center justify-center gap-1.5 rounded-md font-medium transition-colors disabled:cursor-not-allowed ${
        small ? 'px-2.5 py-1 text-xs' : 'px-3.5 py-2 text-sm'
      } ${BUTTONS[variant]} ${className}`}
    />
  )
}

export function Card({ title, actions, children, className = '' }: { title?: ReactNode; actions?: ReactNode; children: ReactNode; className?: string }) {
  return (
    <section className={`rounded-lg border border-slate-200 bg-white shadow-xs ${className}`}>
      {(title || actions) && (
        <header className="flex items-center justify-between gap-3 border-b border-slate-100 px-4 py-3">
          <h2 className="text-sm font-semibold text-slate-800">{title}</h2>
          <div className="flex items-center gap-2">{actions}</div>
        </header>
      )}
      <div className="p-4">{children}</div>
    </section>
  )
}

