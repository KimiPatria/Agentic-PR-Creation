const NUMBER = new Intl.NumberFormat('en-US', { maximumFractionDigits: 2 })

export function money(amount: number | null | undefined, currency = ''): string {
  if (amount === null || amount === undefined) return '-'
  return `${NUMBER.format(amount)}${currency ? ` ${currency}` : ''}`
}

export function dateTime(value: string | null | undefined): string {
  if (!value) return '-'
  return new Date(value).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' })
}

/** SAP "blank" is a real value for account assignment and item category; show it as words. */
export function sapValue(value: string | null | undefined): string {
  if (value === null || value === undefined) return '-'
  return value === '' ? 'blank' : value
}
