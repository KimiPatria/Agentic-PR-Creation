using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Serialization;
using Microsoft.AspNetCore.Diagnostics;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using PrAgent.Api;
using PrAgent.Application;
using PrAgent.Application.Sap;
using PrAgent.Domain;
using PrAgent.Infrastructure;
using PrAgent.Sap.Mock;
using PrAgent.Sap.S4Hana;

var builder = WebApplication.CreateBuilder(args);

// Machine-specific settings (AWS resource names from the CDK stack) live in an untracked file.
builder.Configuration.AddJsonFile("appsettings.Local.json", optional: true, reloadOnChange: false);
builder.Configuration.AddEnvironmentVariables();

builder.Services.ConfigureHttpJsonOptions(o => o.SerializerOptions.Converters.Add(new JsonStringEnumConverter()));
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<ApiExceptionHandler>();

builder.Services.AddApplication();
builder.Services.AddInfrastructure(builder.Configuration);

// ---- The SAP seam: one switch picks the adapter behind ISapReadGateway and ISapPrWriter. ----
var sapMode = builder.Configuration[$"{SapOptions.Section}:Mode"] ?? SapOptions.Mock;
if (sapMode.Equals(SapOptions.S4Hana, StringComparison.OrdinalIgnoreCase)) builder.Services.AddS4HanaSap();
else if (sapMode.Equals(SapOptions.Mock, StringComparison.OrdinalIgnoreCase)) builder.Services.AddMockSap();
else throw new InvalidOperationException($"Sap:Mode '{sapMode}' is not supported. Use {SapOptions.Mock} or {SapOptions.S4Hana}.");

builder.AddPrAgentAuth();

builder.Services.AddOptions<AgentOptions>().BindConfiguration(AgentOptions.Section);
builder.Services.AddHttpClient(AgentEndpoints.HttpClientName, client => client.Timeout = Timeout.InfiniteTimeSpan);

builder.Services.AddMcpServer().WithHttpTransport(o => o.Stateless = true).WithTools<SapReadTools>();

var webOrigins = builder.Configuration.GetSection("Cors:Origins").Get<string[]>() ?? ["http://localhost:5173"];
builder.Services.AddCors(o => o.AddDefaultPolicy(p => p.WithOrigins(webOrigins).AllowAnyHeader().AllowAnyMethod()));

var app = builder.Build();

app.UseExceptionHandler();
app.UseCors();

// The MCP endpoint is for the agent only. It carries no user identity, so it is guarded by a shared
// service token and exposes read-only tools. (Behind AgentCore Gateway this becomes OAuth.)
app.UseWhen(context => context.Request.Path.StartsWithSegments("/mcp"), branch => branch.Use(async (context, next) =>
{
    var expected = context.RequestServices.GetRequiredService<Microsoft.Extensions.Options.IOptions<AgentOptions>>().Value.ServiceToken;
    var supplied = context.Request.Headers[AgentOptions.ServiceTokenHeader].ToString();
    var ok = !string.IsNullOrEmpty(expected)
             && CryptographicOperations.FixedTimeEquals(Encoding.UTF8.GetBytes(supplied), Encoding.UTF8.GetBytes(expected));
    if (!ok)
    {
        context.Response.StatusCode = StatusCodes.Status401Unauthorized;
        await context.Response.WriteAsJsonAsync(new ProblemDetails { Status = 401, Title = "Missing or wrong service token." });
        return;
    }
    await next();
}));

app.UseAuthentication();
app.UseAuthorization();

app.MapGet("/health", () => Results.Ok(new { status = "ok" })).AllowAnonymous();
app.MapMcp("/mcp").AllowAnonymous();

app.MapCommonEndpoints();
app.MapRequestEndpoints();
app.MapAdminEndpoints();
app.MapAgentEndpoints();

if (app.Configuration.GetValue("Database:InitialiseOnStartup", true))
    await DbInitialiser.InitialiseAsync(app.Services);

app.Logger.LogInformation("PR Agent API started. Sap:Mode = {SapMode}, Auth:Mode = {AuthMode}", sapMode, app.Configuration["Auth:Mode"] ?? AuthOptions.Dev);
if (sapMode.Equals(SapOptions.Mock, StringComparison.OrdinalIgnoreCase))
    app.Logger.LogWarning("SAP is SIMULATED. PR numbers are generated by the mock adapter and nothing is written to SAP.");

app.Run();

/// <summary>Turns application exceptions into RFC 7807 problem responses.</summary>
public sealed class ApiExceptionHandler(IProblemDetailsService problems, ILogger<ApiExceptionHandler> logger) : IExceptionHandler
{
    public async ValueTask<bool> TryHandleAsync(HttpContext context, Exception exception, CancellationToken ct)
    {
        var (status, title) = exception switch
        {
            NotFoundException => (StatusCodes.Status404NotFound, "Not found"),
            ForbiddenException => (StatusCodes.Status403Forbidden, "Not allowed"),
            ValidationFailedException => (StatusCodes.Status422UnprocessableEntity, "Validation failed"),
            DomainException => (StatusCodes.Status409Conflict, "Not possible"),
            DbUpdateConcurrencyException => (StatusCodes.Status409Conflict, "Changed by someone else"),
            SapNotConfiguredException => (StatusCodes.Status503ServiceUnavailable, "SAP is not connected"),
            SapException => (StatusCodes.Status502BadGateway, "SAP error"),
            BadHttpRequestException => (StatusCodes.Status400BadRequest, "Bad request"),
            _ => (StatusCodes.Status500InternalServerError, "Unexpected error"),
        };

        if (status == StatusCodes.Status500InternalServerError)
            logger.LogError(exception, "Unhandled exception on {Method} {Path}", context.Request.Method, context.Request.Path);

        var problem = new ProblemDetails
        {
            Status = status,
            Title = title,
            Detail = exception switch
            {
                DbUpdateConcurrencyException => "This request was changed by someone else while you were working on it. Reload and try again.",
                _ when status == StatusCodes.Status500InternalServerError => "Something went wrong on the server. The error has been logged.",
                _ => exception.Message,
            },
        };
        if (exception is ValidationFailedException validation)
            problem.Extensions["evaluation"] = validation.Evaluation;

        context.Response.StatusCode = status;
        return await problems.TryWriteAsync(new ProblemDetailsContext { HttpContext = context, ProblemDetails = problem, Exception = exception });
    }
}

