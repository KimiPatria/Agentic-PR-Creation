using System.Text;
using System.Text.Json;
using Microsoft.Extensions.Options;
using PrAgent.Application.Data;
using PrAgent.Domain;
using PrAgent.Domain.Requests;

namespace PrAgent.Application;

/// <summary>Adds audit rows to the current unit of work, so they commit or roll back with the change they describe.</summary>
public sealed class AuditLog(AppDbContext db, BusinessClock clock)
{
    public static readonly Person System = new("system", "system", "System");

    public void Record(Person actor, string action, string entityType, string entityId, object? data = null)
    {
        db.AuditEvents.Add(new AuditEvent
        {
            At = clock.Now,
            ActorId = actor.Id,
            ActorEmail = actor.Email,
            Action = action,
            EntityType = entityType,
            EntityId = entityId,
            Data = data is null ? null : JsonSerializer.Serialize(data, Json.Options),
        });
    }

    public void Record(Person actor, string action, PurchaseRequest request, object? data = null) =>
        Record(actor, action, "request", request.Id.ToString(), data);
}

public static class Json
{
    public static readonly JsonSerializerOptions Options = new(JsonSerializerDefaults.Web)
    {
        Converters = { new System.Text.Json.Serialization.JsonStringEnumConverter() },
    };
}

/// <summary>Queues the emails of the workflow. They are sent by the outbox after the transaction commits.</summary>
public sealed class Notifier(AppDbContext db, BusinessClock clock, IOptions<AppOptions> options)
{
    public const string SimulatedBanner = "SIMULATED - not in SAP. This PR number was generated by the mock SAP adapter; no purchase requisition exists in SAP.";

    public void RequestSubmitted(PurchaseRequest request, IEnumerable<string> reviewerEmails)
    {
        var body = new StringBuilder()
            .AppendLine($"{request.RequestorName} submitted purchase request {request.Reference} for your review.")
            .AppendLine()
            .AppendLine($"Title: {request.Title}")
            .AppendLine($"Total: {request.Total:N0} {request.Currency} across {request.Lines.Count} line(s)")
            .AppendLine()
            .AppendLine($"Review it: {Link(request)}");
        Queue(request, reviewerEmails, [], $"[PR Agent] {request.Reference} needs your review: {request.Title}", body.ToString());
    }

    public void RequestSentBack(PurchaseRequest request)
    {
        var body = new StringBuilder()
            .AppendLine($"{request.ReviewerName} sent purchase request {request.Reference} back to you.")
            .AppendLine()
            .AppendLine($"Comment: {request.ReviewComment}")
            .AppendLine()
            .AppendLine($"Edit and resubmit: {Link(request)}");
        Queue(request, [request.RequestorEmail], [], $"[PR Agent] {request.Reference} was sent back: {request.Title}", body.ToString());
    }

    public void PrsCreated(PurchaseRequest request)
    {
        var simulated = request.Splits.Any(s => s.IsSimulated);
        var body = new StringBuilder();
        if (simulated) body.AppendLine(SimulatedBanner).AppendLine();

        body.AppendLine($"Purchase request {request.Reference} ({request.Title}) was approved by {request.ReviewerName} and created as {request.Splits.Count} PR(s):")
            .AppendLine();
        foreach (var split in request.Splits.OrderBy(s => s.Sequence))
        {
            var lineNos = request.Lines.Where(l => l.SplitId == split.Id).Select(l => l.LineNo).Order();
            body.AppendLine($"  PR {split.SapPrNumber}{(split.IsSimulated ? " (SIMULATED)" : "")}: lines {string.Join(", ", lineNos)} ({split.Label})");
        }

        body.AppendLine()
            .AppendLine("Next step: approval in SAP according to the Manual of Authority, then procurement.")
            .AppendLine()
            .AppendLine($"Details: {Link(request)}");

        var cc = request.ReviewerEmail is null ? Array.Empty<string>() : [request.ReviewerEmail];
        var numbers = string.Join(", ", request.Splits.OrderBy(s => s.Sequence).Select(s => s.SapPrNumber));
        Queue(request, [request.RequestorEmail], cc, $"[PR Agent] {(simulated ? "SIMULATED " : "")}PR {numbers} created for {request.Reference}", body.ToString());
    }

    private string Link(PurchaseRequest request) => $"{options.Value.WebBaseUrl.TrimEnd('/')}/requests/{request.Id}";

    private void Queue(PurchaseRequest request, IEnumerable<string> to, IEnumerable<string> cc, string subject, string body)
    {
        var recipients = to.Where(e => !string.IsNullOrWhiteSpace(e)).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        if (recipients.Count == 0) return;

        var copies = cc.Where(e => !string.IsNullOrWhiteSpace(e) && !recipients.Contains(e, StringComparer.OrdinalIgnoreCase))
            .Distinct(StringComparer.OrdinalIgnoreCase).ToList();

        db.Outbox.Add(new OutboxMessage
        {
            Id = Guid.NewGuid(),
            Type = OutboxMessage.Email,
            RequestId = request.Id,
            Payload = JsonSerializer.Serialize(new EmailMessage(recipients, copies, subject, body), Json.Options),
            Status = OutboxStatus.Pending,
            CreatedAt = clock.Now,
            NextAttemptAt = clock.Now,
        });
    }
}
